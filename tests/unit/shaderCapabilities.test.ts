import {describe, expect, it} from 'vitest';
import {lightShaderCapabilities, LIGHT_SHADER_CAPABILITIES, MATERIAL_SHADER_CAPABILITIES,
  updateSceneShaderCapabilities} from '../../src/renderer/shaderCapabilities';
import {WGPU_SCENE_FEATURE_BITS} from '../../src/renderer/WGPUSceneFeatures';
import {wgpuMaterialConstants} from '../../src/renderer/wgpuMaterialConstants';
import WGPURayTracePass from '../../src/renderer/WGPURayTracePass';
import MaterialTable from '../../src/renderer/MaterialTable';
import OpenPBRMaterial from '../../src/scene/OpenPBRMaterial';
import Texture from '../../src/scene/Texture';
import {createPlaneGeometry} from '../../src/util/commonGeometry';

const texture = () => new Texture({width: 1, height: 1, data: new Uint8Array([128, 128, 128, 128])});
function materialCapabilities(materials: OpenPBRMaterial[]) {
  return Number(wgpuMaterialConstants(materials, new MaterialTable(materials, []), createPlaneGeometry(), 8).MATERIAL_CAPABILITIES);
}

describe('shader capabilities', () => {
  it('covers transmission generated by map alpha even with a zero scalar weight', () => {
    expect(materialCapabilities([new OpenPBRMaterial()])).toBe(0);
    expect(materialCapabilities([new OpenPBRMaterial({transmissionWeight: .5})]))
      .toBe(MATERIAL_SHADER_CAPABILITIES.transmission);
    expect(materialCapabilities([new OpenPBRMaterial({map: texture(), mapAlphaUsage: 'transmission'})]))
      .toBe(MATERIAL_SHADER_CAPABILITIES.transmission);
    expect(materialCapabilities([new OpenPBRMaterial({mapAlphaUsage: 'transmission'})])).toBe(0);
    expect(materialCapabilities([new OpenPBRMaterial({baseMetalness: .5}), new OpenPBRMaterial({transmissionWeight: 1})]))
      .toBe(MATERIAL_SHADER_CAPABILITIES.metal | MATERIAL_SHADER_CAPABILITIES.transmission);
  });

  it('specializes the current transport combination after parameter edits', () => {
    const pass = Object.create(WGPURayTracePass.prototype) as any;
    pass._constants = {};
    const material = new OpenPBRMaterial();
    const update = () => pass._updateMaterialConstants([material], new MaterialTable([material], []), createPlaneGeometry());
    update(); expect(pass._constants.MATERIAL_CAPABILITIES).toBe(0);
    material.transmissionWeight = 1; update();
    expect(pass._constants.MATERIAL_CAPABILITIES).toBe(MATERIAL_SHADER_CAPABILITIES.transmission);
    material.transmissionWeight = 0; material.baseMetalness = 1; update();
    expect(pass._constants.MATERIAL_CAPABILITIES).toBe(MATERIAL_SHADER_CAPABILITIES.metal);
    material.baseMetalness = 0; update();
    expect(pass._constants.MATERIAL_CAPABILITIES).toBe(0);
  });

  it('updates scene support while leaving current runtime feature values intact', () => {
    const constants: Record<string, boolean | number> = {HAS_COAT: true};
    updateSceneShaderCapabilities(constants);
    expect(constants.SCENE_CAPABILITIES).toBe(WGPU_SCENE_FEATURE_BITS.HAS_COAT);
    constants.HAS_COAT = false; constants.USE_DIFFUSE_MAPS = true;
    updateSceneShaderCapabilities(constants);
    expect(constants.SCENE_CAPABILITIES).toBe(WGPU_SCENE_FEATURE_BITS.USE_DIFFUSE_MAPS);
    expect(constants.HAS_COAT).toBe(false);
  });

  it('includes each analytic kind and emissive geometry without depending on counts', () => {
    const kinds = ['SphereLight', 'RectLight', 'SpotLight', 'DirectionalLight'] as const;
    expect(lightShaderCapabilities([], 0)).toBe(0);
    expect(lightShaderCapabilities([], 1)).toBe(LIGHT_SHADER_CAPABILITIES.emissive);
    for (const type of kinds) {
      expect(lightShaderCapabilities([type, type], 0)).toBe(LIGHT_SHADER_CAPABILITIES[type]);
    }
    expect(lightShaderCapabilities(kinds, 8)).toBe(31);
  });
});
