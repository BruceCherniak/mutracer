// Build the scene with Three.js (GLTFLoader, OrbitControls, standard and
// physical materials) and path trace it with MuTracer.
import * as THREE from 'three';
import { GLTFLoader } from 'three/examples/jsm/loaders/GLTFLoader.js';
import { OrbitControls } from 'three/examples/jsm/controls/OrbitControls.js';
import {
  Engine, Render,
  fromTHREECamera,
  THREESceneSync
} from '@meimu/mutracer';
import { createSkyTexture } from './shared/sky';
import { showStatus } from './shared/status';
import { exampleSelection } from './shared/progressive';

const canvas = document.getElementById('main') as HTMLCanvasElement;
const statusElement = document.getElementById('status')!;
const rotateInput = document.getElementById('rotate') as HTMLInputElement;
const roughnessInput = document.getElementById('roughness') as HTMLInputElement;

// --- Three.js scene -------------------------------------------------------
const threeScene = new THREE.Scene();

// Equirectangular HDR environment, used for lighting and as the background.
const sky = createSkyTexture().image as { data: Float32Array; width: number; height: number };
const environment = new THREE.DataTexture(
  sky.data, sky.width, sky.height, THREE.RGBAFormat, THREE.FloatType
);
environment.mapping = THREE.EquirectangularReflectionMapping;
environment.needsUpdate = true;
threeScene.environment = environment;
threeScene.background = environment;

const board = new THREE.Mesh(
  new THREE.BoxGeometry(4, 0.1, 2.4),
  new THREE.MeshPhysicalMaterial({
    color: 0x6b4a2f,
    roughness: 0.35,
    clearcoat: 0.6,
    clearcoatRoughness: 0.1
  })
);
board.position.y = -0.05;
threeScene.add(board);

const sun = new THREE.DirectionalLight(0xfff2e0, 2.5);
sun.position.set(3, 5, 2);
threeScene.add(sun);

const pieces = new THREE.Group();
threeScene.add(pieces);
// chess.glb is generated by scripts/create-example-model.mjs (CC0).
const gltf = await new GLTFLoader().loadAsync('./assets/chess.glb');
pieces.add(gltf.scene);

const threeCamera = new THREE.PerspectiveCamera(35, 1, 0.1, 100);
threeCamera.position.set(2.2, 2, 4.5);
const orbit = new OrbitControls(threeCamera, canvas);
orbit.target.set(0, 0.4, 0);
orbit.update();

// --- MuTracer ---------------------------------------------------------------
const engine = new Engine({canvas, backend: new URLSearchParams(location.search).has('webgl') ? 'webgl' : 'auto'});
const preview = new Render(engine, {resolutionScale: .5, adaptiveResolution: {targetFrameMs: 20, minScale: .25}, bounces: 2, bevel: false, dispersionWavelengths: 1, directLightCandidates: 2});
const final = new Render(engine, {fallback: preview, bounces: 6, maxSamples: 512});
const select = exampleSelection(engine, preview, final);
const camera = fromTHREECamera(threeCamera); engine.camera = camera;

const sync = new THREESceneSync(threeScene);
engine.scene = sync.scene;
roughnessInput.addEventListener('input', () => {
  board.material.roughness = Number(roughnessInput.value);
});
window.addEventListener('pagehide', () => { sync.dispose(); engine.dispose(); });

function resize() {
  const ratio = Math.min(window.devicePixelRatio, 2);
  engine.display.setSize(canvas.clientWidth * ratio, canvas.clientHeight * ratio);
  threeCamera.aspect = canvas.clientWidth / canvas.clientHeight;
  threeCamera.updateProjectionMatrix();
}
window.addEventListener('resize', resize);
resize();

let lastTime = performance.now();
function frame(time: number) {
  const delta = (time - lastTime) / 1000;
  lastTime = time;
  if (rotateInput.checked) {
    // Both backends refit the changed instance transforms.
    pieces.rotation.y += delta * 0.3;
  }
  sync.update();
  camera.copy(fromTHREECamera(threeCamera));
  const current = select(engine.update()); const status = current.refine();
  const shown = engine.display.present(current);
  showStatus(statusElement, engine, final, shown === preview ? 'previewing' : status);
  requestAnimationFrame(frame);
}
requestAnimationFrame(frame);
