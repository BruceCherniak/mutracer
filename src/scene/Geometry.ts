import { vec3 } from '../math.js';
import { FlattendBVH } from '../renderer/bvhAccel.js';

type AttributeData = Float32Array | Uint16Array | Uint32Array | Int32Array;
export class Attribute<T extends AttributeData = AttributeData> {
  array: T;
  itemSize: number;
  constructor(array: T, itemSize: number) {
    this.array = array;
    this.itemSize = itemSize;
  }

  static getItem(attr: Attribute, out: number[], vertexIndex: number) {
    const array = attr.array;
    const itemSize = attr.itemSize;
    const offset = vertexIndex * itemSize;
    for (let i = 0; i < itemSize; i++) {
      out[i] = array[offset + i];
    }
  }

  static getCount(attr: Attribute) {
    return attr.array.length / attr.itemSize;
  }
}

export type AttributeName =
  | 'position'
  | 'normal'
  | 'tangent'
  | 'uv'
  | 'uv1'
  | 'color';
export const AVAILABLE_ATTRIBUTES: AttributeName[] = [
  'position',
  'normal',
  'tangent',
  'uv',
  'uv1',
  'color'
];

export type GeometryData = Record<AttributeName, Attribute<Float32Array>> & {
  /** Required triangle vertex indices; three entries per triangle. */
  indices: Attribute<Uint16Array | Uint32Array>;
  materialIndex: Attribute<Int32Array>;
};

/**
 * Indexed triangle mesh data. `position`, `normal` and `indices` are required;
 * `normal` can be generated with `generateVertexNormals()`.
 */
export default class Geometry {
  /** Incremented by either update method. Default `0`. */
  version = 0;
  private _topologyVersion = 0;
  /** Index/material-index revision, advanced by markUpdated(). Default `0`. */
  get topologyVersion() { return this._topologyVersion; }
  /**
   * Hint that vertices change often (skinning, morph targets). Keeps a built-in
   * BVH2 layout that can be refit in place. Default `false`.
   */
  dynamic = false;
  /** Required vertex positions in scene units; provided by the constructor. */
  position: Attribute<Float32Array>;
  /** Required vertex normals; provided by the constructor or generated by the caller. */
  normal: Attribute<Float32Array>;
  /** Optional vertex tangents. Default undefined. */
  tangent?: Attribute<Float32Array>;
  /** Optional primary texture coordinates. Default undefined. */
  uv?: Attribute<Float32Array>;
  /** Optional secondary UV set (glTF TEXCOORD_1 / Three.js uv1). Default undefined. */
  uv1?: Attribute<Float32Array>;
  /** Optional vertex RGB colors. Default undefined. */
  color?: Attribute<Float32Array>;
  /** Required triangle vertex indices; three entries per triangle. */
  indices: Attribute<Uint16Array | Uint32Array>;
  /** Optional per-triangle material indices; default undefined selects material 0. */
  materialIndex?: Attribute<Int32Array>;

  /** Bottom-level BVH, built automatically before rendering. @internal */
  bvh?: FlattendBVH;

  /** Local-space bounds in scene units; initial min/max are `[0, 0, 0]`. */
  boundingBox = {
    min: vec3.create(),
    max: vec3.create()
  };
  constructor(data?: Partial<GeometryData>) {
    data = data || {};
    this.indices = data.indices!;
    this.position = data.position!;
    this.normal = data.normal!;

    this.tangent = data.tangent;
    this.uv = data.uv;
    this.uv1 = data.uv1;
    this.color = data.color;
    this.materialIndex = data.materialIndex;
  }

  /**
   * Call after editing attribute arrays or replacing attributes. Increments
   * version so the next render refits or rebuilds the BVH automatically.
   * Replacing a mesh's Geometry object is detected without this call.
   */
  markUpdated() {
    this._topologyVersion++;
    this.version++;
    return this;
  }

  /**
   * Call after editing vertex attributes without changing indices or materialIndex.
   * Advances version while preserving topologyVersion, allowing vertex-only uploads.
   */
  markVerticesUpdated() {
    this.version++;
    return this;
  }

  /** Returns the number of vertices in the position attribute. */
  static getVertexCount(geo: Geometry) {
    return geo.position.array.length / geo.position.itemSize;
  }

  /** Packs a material index and 8-bit weight for internal buffers. @internal */
  static packMaterialIndexAndWeightToInt(index: number, weight: number) {
    return Math.round(weight * 255) + (index << 8);
  }

  /** Unpacks an internal material index and weight. @internal */
  static unpackMaterialIndexAndWeightFromInt(int: number) {
    return [int >> 8, (int & 0xff) / 255];
  }
}
